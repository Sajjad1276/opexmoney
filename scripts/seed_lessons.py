async def seed() -> None:
    async with async_session() as session:
        async with session.begin():
            for data in LESSONS:
                existing = await session.scalar(
                    select(Lesson).where(
                        Lesson.module_id == data["module_id"],
                        Lesson.order == data["order"],
                    )
                )
                if existing is not None:
                    print(
                        f"  skip: Module {data['module_id']}.{data['order']} exists"
                    )
                    continue

                session.add(Lesson(**data))
                print(f"  add: {data['title_fa']}")

    print("Done.")


if __name__ == "__main__":
    asyncio.run(seed())
